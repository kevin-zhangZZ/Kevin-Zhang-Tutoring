"""Write src/tools/study-score/subjects.gen.ts: every subject's details and exam grade distributions.

Usage: python -I scripts/study-score/build.py <catalog.json>

catalog.json comes from parse_all.py + catalog.py (VCAA's grade-distribution PDFs, every graded
assessment parsed and checked). Subject details come from core-subjects.json (hand-checked) and
exam-totals.json (raw totals and weights from VCAA's examination specifications).

Rules:
- A year is used only if at least MIN_COHORT students sat its exam(s), and only if it has every
  graded assessment the subject's inputs feed.
- A subject is listed only with at least MIN_YEARS such years, or, for a new study (Politics,
  first examined 2025), when its newest year had at least NEW_STUDY_COHORT students.
- Each input's weight is its stated percentage of the study score; without percentages (most
  single-exam subjects), each graded assessment counts by its own GA scale, as VCAA reports it.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'src', 'tools', 'study-score', 'subjects.gen.ts')
MIN_COHORT = 10
MIN_YEARS = 3
NEW_STUDY_COHORT = 100

catalog = json.load(open(sys.argv[1]))
core = {k: v for k, v in json.load(open(os.path.join(HERE, 'core-subjects.json'))).items() if not k.startswith('_')}
extra_path = os.path.join(HERE, 'exam-totals.json')
extra = {k: v for k, v in json.load(open(extra_path)).items() if not k.startswith('_')} if os.path.exists(extra_path) else {}

order = list(core) + sorted(extra, key=lambda s: (extra[s]['group'], extra[s]['name']))
subjects, dists, log = {}, {}, []

for study in order:
    meta = core.get(study) or extra[study]
    if study not in catalog:
        log.append(f'{study}: not in catalog')
        continue
    inputs = meta['inputs']
    gas = sorted({i['ga'] for i in inputs})
    years = []
    for y in sorted(catalog[study], key=int):
        row = catalog[study][y]
        ex = {int(g): d for g, d in row['exams'].items()}
        if not all(g in ex for g in gas):
            log.append(f'{study} {y}: missing GA {[g for g in gas if g not in ex]}')
            continue
        if any(sum(1 for b in ex[g]['bands'] if b[2] > 0) < 2 for g in gas):
            log.append(f'{study} {y}: everyone in one grade')
            continue
        cohort = ex[gas[-1]]['total']
        if cohort < MIN_COHORT:
            log.append(f'{study} {y}: only {cohort} students')
            continue
        years.append({'year': int(y), 'exams': [{'max': ex[g]['max'], 'bands': ex[g]['bands']} for g in gas], 'source': row['url'], 'cohort': cohort})
    if len(years) < MIN_YEARS and not (years and years[-1]['cohort'] >= NEW_STUDY_COHORT):
        log.append(f'{study}: dropped, {len(years)} usable years')
        continue

    newest = years[-1]
    have_pct = all(i.get('percent') for i in inputs)
    out_inputs = []
    for i in inputs:
        g = gas.index(i['ga'])
        same = [j for j in inputs if j['ga'] == i['ga']]
        if len(same) > 1 and not have_pct:
            raise SystemExit(f'{study}: inputs sharing GA{i["ga"]} need percentages')
        weight = i['percent'] if have_pct else newest['exams'][g]['max']
        e = {'label': i['label'], 'short': i.get('short') or ('Exam' if i['label'] == 'Exam' else i['label']), 'rawMax': i['raw_max'], 'ga': g, 'weight': weight}
        if i.get('older'):
            e['older'] = [{'upTo': o['up_to'], 'rawMax': o['raw_max']} for o in sorted(i['older'], key=lambda o: o['up_to'])]
        out_inputs.append(e)
    # Weighted: a mark isn't worth the same on every input (weight per mark differs), so totals
    # are counted as a weighted percentage. Inputs on their own GA without percentages count in GA
    # points, worth (GA max / raw max) each.
    per_mark = [e['weight'] / e['rawMax'] for e in out_inputs]
    weighted = max(per_mark) - min(per_mark) > 1e-9
    info = {
        'name': meta['name'], 'label': meta['label'], 'group': meta['group'], 'aliases': meta.get('aliases', ''),
        # No stated start of the current design (VCE VET): treat every paper shown as current.
        'exams': out_inputs, 'designFrom': meta['design_from'] or years[0]['year'],
    }
    if weighted:
        info['weighted'] = True
    if meta.get('older_name'):
        info['olderName'] = {'upTo': meta['older_name']['up_to'], 'name': meta['older_name']['name']}
    alltitles = ' '.join(t for t, _ in catalog[study][str(newest['year'])]['all'].values())
    if 'SCHOOL-ASSESSED TASK' in alltitles.upper():
        info['tasks'] = True
    subjects[meta['id']] = info
    dists[meta['id']] = years


def ts(v, ind=0):
    return json.dumps(v, ensure_ascii=False)


lines = [
    '// GENERATED by scripts/study-score/build.py from VCAA grade distributions and examination',
    '// specifications. Do not edit by hand: change core-subjects.json / exam-totals.json and re-run.',
    "import type { SubjectInfo, YearDist } from './data.ts'",
    '',
    'export const SUBJECT_DATA = {',
]
for sid, info in subjects.items():
    lines.append(f'  {json.dumps(sid)}: {ts(info)},')
lines.append('} satisfies Record<string, SubjectInfo>')
lines.append('')
lines.append('export const DISTRIBUTION_DATA: Record<keyof typeof SUBJECT_DATA, YearDist[]> = {')
for sid, ys in dists.items():
    lines.append(f'  {json.dumps(sid)}: [')
    for y in ys:
        ex = ', '.join('{ max: %d, bands: %s }' % (e['max'], json.dumps(e['bands'])) for e in y['exams'])
        lines.append(f"    {{ year: {y['year']}, exams: [{ex}], source: {json.dumps(y['source'])} }},")
    lines.append('  ],')
lines.append('}')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print(len(subjects), 'subjects,', sum(len(v) for v in dists.values()), 'year tables ->', os.path.relpath(OUT, ROOT))
for l in log:
    print('  ', l)
